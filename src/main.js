function isUnitAlive(unit) {

 

    if (!unit) {

        return false;

    }

 

    if (unit.destroyed === true) {

        return false;

    }

 

    const strength =

        Number(unit.strength);

 

    const manpower =

        Number(unit.manpower);

 

    // 任意一个有效兵力字段 <= 0，都视为阵亡

    if (

        Number.isFinite(strength) &&

        strength <= 0

    ) {

        return false;

    }

 

    if (

        Number.isFinite(manpower) &&

        manpower <= 0

    ) {

        return false;

    }

 

    return true;

}

 

 

